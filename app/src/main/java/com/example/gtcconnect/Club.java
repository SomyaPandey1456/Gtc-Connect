package com.example.gtcconnect;

public class Club {
    private String _id;
    private String club_name;
    private String club_image;
    private String div_name;
    private String club_desc;
    private String head1_name;
    private String head1_image;
    private String head2_name;
    private String head2_image;

    // Getters and setters
    public String getId() {
        return _id;
    }

    public void setId(String _id) {
        this._id = _id;
    }

    public String getClubName() {
        return club_name;
    }

    public void setClubName(String club_name) {
        this.club_name = club_name;
    }

    public String getClubImage() {
        return club_image;
    }

    public void setClubImage(String club_image) {
        this.club_image = club_image;
    }

    public String getDivName() {
        return div_name;
    }

    public void setDivName(String div_name) {
        this.div_name = div_name;
    }

    public String getClubDesc() {
        return club_desc;
    }

    public void setClubDesc(String club_desc) {
        this.club_desc = club_desc;
    }

    public String getHead1Name() {
        return head1_name;
    }

    public void setHead1Name(String head1_name) {
        this.head1_name = head1_name;
    }

    public String getHead1Image() {
        return head1_image;
    }

    public void setHead1Image(String head1_image) {
        this.head1_image = head1_image;
    }

    public String getHead2Name() {
        return head2_name;
    }

    public void setHead2Name(String head2_name) {
        this.head2_name = head2_name;
    }

    public String getHead2Image() {
        return head2_image;
    }

    public void setHead2Image(String head2_image) {
        this.head2_image = head2_image;
    }
}
